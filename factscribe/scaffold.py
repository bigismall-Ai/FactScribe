def _normalise_derived(raw) -> list[str]:
    if not raw:
        return []
    if isinstance(raw, str):
        raw = raw.split(",")
    out = []
    for item in raw:
        text = str(item).strip()
        if text:
            out.append(text)
    return out


def render_fact_block(*, fid: str, claim: str, value: str, source: str,
                      source_sha256: str, locator: str, confidence: str,
                      derived_from: list[str] | None = None,
                      expr: str = "", note: str = "") -> str:
    """一条 `[[fact]]`（字段顺序与 examples/minimal 一致，便于人读）。"""
    lines = [
        "[[fact]]",
        "id = %s" % toml_string(fid),
        "claim = %s" % toml_string(claim),
        "value = %s" % toml_string(value),
        "source = %s" % toml_string(source),
        "source_sha256 = %s" % toml_string(source_sha256),
        "locator = %s" % toml_string(locator),
        "confidence = %s" % toml_string(confidence),
        "derived_from = %s" % toml_array(derived_from or []),
    ]
    if expr:
        lines.append("expr = %s" % toml_string(expr))
    if note:
        lines.append("note = %s" % toml_string(note))
    return "\n".join(lines) + "\n"


def _check_source(root: Path, cfg, source: str) -> tuple[str, Path]:
    """校验并归一化 source；返回 (posix 相对路径, 磁盘绝对路径)。"""
    raw = str(source or "").strip()
    if not raw:
        raise ConfigError("--source 必填：事实必须指向一个原始产物")
    if re.match(r"^[A-Za-z][A-Za-z0-9+.-]*://", raw):
        raise ConfigError("--source 必须是项目内的相对路径，不收 URL：%s" % raw)
    rel_path = Path(raw)
    if rel_path.is_absolute() or ".." in rel_path.parts:
        raise ConfigError("--source 必须是项目内的相对路径（不许绝对路径或 ..）：%s" % raw)
    rel = rel_path.as_posix()

    if cfg.source_root.strip():
        # 配了 source_root：与 audit 同口径，相对它解析（可能在项目外）
        from .audit import source_base
        base = source_base(cfg)
        full = base / rel
        try:
            full.resolve().relative_to(base.resolve())
        except ValueError:
            raise ConfigError("--source 越出 source_root：%s" % raw)
    else:
        results = (root / cfg.source_dir).resolve()
        full = root / rel
        try:
            full.resolve().relative_to(results)
        except ValueError:
            raise ConfigError(
                "--source 必须放在 %s/ 下（v1 约定）——收到 %s；"
                "原始产物请先复制到 %s/，跨目录请配 project.source_root"
                % (cfg.source_dir, raw, cfg.source_dir))
    full = full.resolve()
    if not full.is_file():
        raise ConfigError("--source 文件不存在：%s（要找的是 %s）" % (raw, full))
    return rel, full


def add_fact(root: Path, *, fid: str, claim: str, value: str, source: str,
             locator: str = "", confidence: str = "med", expr: str = "",
             derived_from=None, note: str = "") -> dict:
    """往 facts/01-core.toml 追加一条事实；返回落账信息（含 sha256）。"""
    root = Path(root)
    cfg = load_config(root)
    if cfg.is_v3:
        raise ConfigError("fact add 目前只支持 v1 项目（[project] 表；"
                          "V3 的审批目标请按 SPEC-V3.0 写在 schema 声明里）")
    known = load_facts(cfg)
    ledger = root / FACTS_FILE
    if ledger.is_file():
        load_toml(ledger)  # 账坏了就别往上追加

    fid = str(fid or "").strip()
    if not fid:
        raise ConfigError("--id 必填：账本键是事实的唯一入账键")
    if not _ID_RE.fullmatch(fid) or re.search(r"\s", fid):
        raise ConfigError(
            "fact id %r 不合法：只允许字母开头，后接字母/数字/_ . : -（不许空白）"
            % fid)
    for f in known:
        if f.id_key == fid.casefold():
            raise ConfigError(
                "fact id %r 已存在（%s）——id 按大小写不敏感判重；"
                "改数请新增一条并写 supersedes" % (fid, f.file))
    claim = str(claim or "").strip()
    value = str(value or "").strip()
    if not claim:
        raise ConfigError("--claim 必填：说清这条事实到底主张什么")
    if not value:
        raise ConfigError("--value 必填：value 是正文要绑的那个数字原文")
    locator = str(locator or "").strip()
    if confidence not in CONFIDENCE_OK:
        raise ConfigError("--confidence 只认 %s，收到 %r"
                          % (" / ".join(sorted(CONFIDENCE_OK)), confidence))
    parents = _normalise_derived(derived_from)
    expr = str(expr or "").strip()
    if parents and not expr:
        raise ConfigError(
            "--derived-from 给了就必须同时给 --expr：推算式是机器复核推算值的唯一依据")

    rel, full = _check_source(root, cfg, source)
    sha = sha256_file(full)

    block = render_fact_block(
        fid=fid, claim=claim, value=value, source=rel, source_sha256=sha,
        locator=locator, confidence=confidence, derived_from=parents,
        expr=expr, note=str(note or "").strip())

    ledger.parent.mkdir(parents=True, exist_ok=True)
    if ledger.is_file():
        existing = ledger.read_bytes()
    else:
        existing = _FACTS_TOML["zh"].encode("utf-8")
    sep = b""
    if existing:
        if not existing.endswith(b"\n"):
            sep += b"\n"
        sep += b"\n"
    ledger.write_bytes(existing + sep + block.encode("utf-8"))

    manifest_line = "%s = %s" % (toml_string(rel), toml_string(sha))
    return {
        "id": fid,
        "claim": claim,
        "value": value,
        "source": rel,
        "source_sha256": sha,
        "locator": locator,
        "confidence": confidence,
        "derived_from": parents,
        "expr": expr,
        "note": str(note or "").strip(),
        "ledger": FACTS_FILE,
        "manifest": cfg.manifest,
        "manifest_line": manifest_line,
    }
