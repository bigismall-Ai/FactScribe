# v1 的 id 口径（与 audit.run_check 的 BAD_ID_FORMAT 判据一致）
_ID_RE = re.compile(r"[A-Za-z][A-Za-z0-9_.:-]*")

_TEX_ESCAPE = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(text: str) -> str:
    """把标题/作者里的 LaTeX 特殊字符转义，避免生成的 main.tex 编不过。"""
    return "".join(_TEX_ESCAPE.get(ch, ch) for ch in str(text or ""))


def toml_string(text: str) -> str:
    """TOML 基本字符串（与 config 的 mini 解析器兼容的最小转义集）。"""
    out = (str(text or "")
           .replace("\\", "\\\\")
           .replace('"', '\\"')
           .replace("\n", "\\n")
           .replace("\r", "\\r")
           .replace("\t", "\\t"))
    return '"%s"' % out


def toml_array(items) -> str:
    return "[%s]" % ", ".join(toml_string(x) for x in items)


