def _render(lang: str, title: str, author: str) -> dict[str, str]:
    """七个文件的全部内容。同参数 → 逐字节一致（无时间戳、无绝对路径）。"""
    authors = [author] if author else []
    author_tex = tex_escape(author) if author else ""
    author_line = (("作者：%s。" if lang == "zh" else "by %s.") % author
                   if author else "")
    mapping = {
        "paperkit.toml": (_PAPERKIT[lang]
                          .replace("__TITLE__", toml_string(title))
                          .replace("__AUTHORS__", toml_array(authors))),
        "main.tex": (_MAIN_TEX[lang]
                     .replace("__TITLE_TEX__", tex_escape(title))
                     .replace("__AUTHOR_TEX__", author_tex)),
        "sections/01-intro.tex": _INTRO_TEX[lang],
        FACTS_FILE: _FACTS_TOML[lang],
        MANIFEST_FILE: _MANIFEST_TOML[lang],
        "refs.bib": _REFS_BIB[lang],
        "README.md": (_README[lang]
                      .replace("__TITLE__", title)
                      .replace("__AUTHOR_LINE__", author_line)),
    }
    return {name: mapping[name] for name in INIT_FILES}


def init_project(root: Path, *, title: str | None = None,
                 author: str | None = None, lang: str = "zh",
                 force: bool = False) -> dict:
    """落盘最小项目骨架。非空目录需 force=True；覆盖同名文件，不动别的文件。"""
    if lang not in LANGS:
        raise ConfigError("--lang 只认 %s，收到 %r" % (" / ".join(LANGS), lang))
    root = Path(root)
    if root.exists() and not root.is_dir():
        raise ConfigError("目标 %s 已存在且不是目录——不敢往文件里写" % root)
    if root.is_dir() and any(root.iterdir()) and not force:
        raise ConfigError(
            "目标目录 %s 非空（里面已有东西）——换一个空目录，或加 --force "
            "覆盖本命令生成的同名文件（其他文件不动）" % root)

    clean_title = (title or "").strip() or DEFAULT_TITLE[lang]
    clean_author = (author or "").strip()
    files = _render(lang, clean_title, clean_author)

    root.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        dest = root / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(text.encode("utf-8"))

    return {
        "root": str(root),
        "lang": lang,
        "title": clean_title,
        "authors": [clean_author] if clean_author else [],
        "force": bool(force),
        "files": list(INIT_FILES),
        "next": [line.format(d=root) for line in _NEXT_STEPS[lang]],
    }


